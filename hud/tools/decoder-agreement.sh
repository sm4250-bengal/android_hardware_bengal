#!/bin/bash
# decoder-agreement.sh -- prove that this daemon's MCU parser and PID 1's are
# the same parser.
#
# WHY. There are now three implementations of the XYAUTO frame format:
#
#   apps/mcu-toolbox/bridge/main.go      checksumOK():2365, scanner :2430
#   kernel/initramfs/diagnostic-init.c   mcu_checksum():2251, mcu_next_frame():2286
#   platform/hardware/xyauto/hud/src/mcu/mod.rs        (this daemon)
#
# The first two produced every capture this project has. If the third disagrees
# with them, a frame the unit really sent is decoded differently by the thing
# that will act on it -- and the disagreement would show up as a behaviour bug
# on the bench, weeks later, with no obvious cause.
#
# HOW. PID 1's three decoder functions are self-contained: they depend only on
# MCU_H0, MCU_H1 and MCU_FRAME_MAX. This script LIFTS them verbatim out of
# diagnostic-init.c by name -- it does not copy them, so it cannot drift -- adds
# a main(), compiles with cc, runs both decoders over the same inputs and
# compares.
#
# The comparison is a committed golden file, tools/decoder-agreement.golden:
#   * this script regenerates it from the C side;
#   * the Rust test `agrees_with_pid_1_on_the_golden_captures` asserts against
#     it with include_str!.
# So a change on EITHER side moves one half of the assert and fails loudly.
#
#   ./tools/decoder-agreement.sh            check (regenerate + git diff)
#   ./tools/decoder-agreement.sh --write    accept a new golden
#
# Desk-only. Needs cc and nothing else; no Android tree, no network.

set -eu

here=$(cd "$(dirname "$0")" && pwd)
hud=$(dirname "$here")
repo=$(cd "$hud/../../../.." && pwd)
init_c="$repo/kernel/initramfs/diagnostic-init.c"
golden="$here/decoder-agreement.golden"
write=0
[ "${1:-}" = "--write" ] && write=1

[ -f "$init_c" ] || { echo "decoder-agreement: no $init_c" >&2; exit 2; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# --- lift ------------------------------------------------------------------
# Extract a top-level function by name: from its `static ... name(` line to the
# first line that is exactly "}". Fails loudly if the function is not found,
# which is the point -- a rename must not silently disable this gate.
lift() {
	local name=$1
	awk -v want="$name" '
		$0 ~ ("^static .*[^a-zA-Z0-9_]" want "\\(") { inside = 1 }
		inside { print }
		inside && /^\}$/ { inside = 0; found = 1 }
		END { if (!found) exit 1 }
	' "$init_c" || { echo "decoder-agreement: $name not found in $init_c" >&2; exit 3; }
}

{
	echo "/* GENERATED by tools/decoder-agreement.sh -- do not edit, do not commit."
	echo " * Lifted verbatim from kernel/initramfs/diagnostic-init.c. */"
	echo "#include <stdio.h>"
	echo "#include <string.h>"
	echo "#include <stdlib.h>"
	# the three defines the lifted code needs, taken from the same file
	grep -E '^#define (MCU_H0|MCU_H1|MCU_FRAME_MAX) ' "$init_c"
	echo
	lift mcu_checksum
	echo
	lift mcu_next_frame
	echo
	lift mcu_frame_ok
} > "$tmp/lifted.c"

for fn in mcu_checksum mcu_next_frame mcu_frame_ok; do
	grep -q "$fn" "$tmp/lifted.c" || { echo "decoder-agreement: lift lost $fn" >&2; exit 3; }
done

# --- a main() that speaks the same canonical form as the Rust test ----------
cat >> "$tmp/lifted.c" <<'EOF'

/* Read one hex byte string per line ("# name" starts a case), decode it the
 * way PID 1 does, and print the canonical form the Rust side produces. */
static void emit_frame(const unsigned char *f, int total)
{
	int i;
	printf("frame %s ", mcu_frame_ok(f, total) ? "ok " : "bad");
	for (i = 0; i < total; i++)
		printf("%s%02x", i ? " " : "", f[i]);
	printf("\n");
}

int main(void)
{
	char line[8192];

	while (fgets(line, sizeof line, stdin)) {
		unsigned char buf[4096];
		int len = 0, i = 0;
		unsigned long valid = 0, bad = 0, discarded = 0;
		char *p;

		if (line[0] == '#') { fputs(line, stdout); continue; }
		for (p = line; *p; p++) {
			unsigned v;
			if (*p == ' ' || *p == '\n') continue;
			if (sscanf(p, "%2x", &v) != 1) break;
			buf[len++] = (unsigned char)v;
			p++;
		}
		if (len == 0) continue;

		for (;;) {
			int skipped = 0, total = 0;
			if (!mcu_next_frame(buf + i, len - i, &skipped, &total)) {
				if (skipped > 0) {
					printf("discard %d BeforeHeader\n", skipped);
					discarded += skipped;
					i += skipped;
				}
				break;
			}
			if (skipped > 0) {
				/* PID 1 does not distinguish the two discard
				 * reasons; the Rust side does, so replay the
				 * scan to label them the same way. */
				int k = 0;
				while (k < skipped) {
					if (buf[i + k] == MCU_H0 && i + k + 2 < len &&
					    buf[i + k + 1] == MCU_H1) {
						printf("discard 1 ImpossibleLength(%d)\n",
						       buf[i + k + 2]);
						discarded += 1;
						k += 1;
					} else {
						int run = 0;
						while (k + run < skipped &&
						       !(buf[i + k + run] == MCU_H0 &&
							 i + k + run + 2 < len &&
							 buf[i + k + run + 1] == MCU_H1))
							run++;
						printf("discard %d BeforeHeader\n", run);
						discarded += run;
						k += run;
					}
				}
				i += skipped;
			}
			emit_frame(buf + i, total);
			if (mcu_frame_ok(buf + i, total)) valid++; else bad++;
			i += total;
		}
		printf("stats valid=%lu bad=%lu discarded=%lu pending=%d\n",
		       valid, bad, discarded, len - i);
	}
	return 0;
}
EOF

cc -O1 -Wall -Wno-unused-function -o "$tmp/lifted" "$tmp/lifted.c"

# --- the inputs. KEEP IN STEP with golden_inputs() in src/mcu/mod.rs -------
# d3-0043-capture is the real 78-byte receive stream, reconstructed from
# PID 1's own log (result.log:112-122 lists the frames; :111 says 78 bytes,
# and 11 + 13 + 9*6 = 78 exactly).
cat > "$tmp/inputs" <<'EOF'
# d3-0043-capture
5aa508330022007dfe09275aa50a2101250008010120008f5aa50312 04ea5aa5031204ea5aa5031201ed5aa5031204ea5aa5031207e75aa5031201ed5aa5031207e75aa5031201ed5aa5030511ea
# corrupt-checksum
5aa508330022007dfe09275aa50a2101250008010120008f5aa50312 04eb5aa5031204ea5aa5031201ed5aa5031204ea5aa5031207e75aa5031201ed5aa5031207e75aa5031201ed5aa5030511ea
# garbage-then-frame
00ff5a01dead5aa5031204ea
# impossible-length
5aa5005aa5031204ea
# lone-5a-tail
5aa5031204ea5a
EOF
sed -i 's/ //g; s/^#/# /' "$tmp/inputs"

"$tmp/lifted" < "$tmp/inputs" > "$tmp/out"

if [ "$write" = 1 ]; then
	cp "$tmp/out" "$golden"
	echo "decoder-agreement: wrote $golden"
	exit 0
fi

if [ ! -f "$golden" ]; then
	echo "decoder-agreement: $golden does not exist; run with --write" >&2
	exit 1
fi

if diff -u "$golden" "$tmp/out"; then
	echo "decoder-agreement: PID 1's decoder still produces the committed golden"
	echo "decoder-agreement: (the Rust side is checked against the same file by"
	echo "                    the agrees_with_pid_1_on_the_golden_captures test)"
else
	echo "decoder-agreement: REFUSED -- kernel/initramfs/diagnostic-init.c's parser" >&2
	echo "no longer produces the committed golden. Either it changed on purpose" >&2
	echo "(re-run with --write and check the Rust test still passes) or it" >&2
	echo "regressed." >&2
	exit 1
fi
